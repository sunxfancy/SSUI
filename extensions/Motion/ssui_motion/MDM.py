"""Isolated official MDM inference with portable joint trajectories."""
from dataclasses import dataclass
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import numpy as np
from ssui.annotation import param
from ssui.base import Prompt, Video
from ssui.config import SSUIConfig
from ssui.controller import Random, Slider


@dataclass
class Motion:
    joints: np.ndarray  # frames, 22 HumanML joints, XYZ in meters
    fps: float
    output_dir: Path
    text: str

    def export(self, path: str):
        np.savez_compressed(path, joints=self.joints, fps=self.fps, text=self.text)

    def preview(self) -> Video:
        import imageio.v3 as iio
        from PIL import Image
        frames = [Image.fromarray(frame) for frame in
                  iio.imiter(self.output_dir / 'samples_00_to_00.mp4')]
        return Video('mp4', frames, fps=int(self.fps), artifacts={'motion.npz': str(self.output_dir / 'motion.npz')})


class MDMModel:
    def __init__(self, repository: Path = None, checkpoint: Path = None, python: str = ""):
        self.repository = repository
        self.checkpoint = checkpoint
        self.python = python

    @staticmethod
    def load(repository_path: str, checkpoint_path: str, python_path: str = '') -> 'MDMModel':
        repository = Path(repository_path).resolve()
        checkpoint = Path(checkpoint_path)
        if not checkpoint.is_absolute():
            checkpoint = repository / checkpoint
        if not (repository / 'sample/generate.py').is_file():
            raise ValueError('MDM repository must contain sample/generate.py')
        if not checkpoint.is_file() or not checkpoint.with_name('args.json').is_file():
            raise ValueError('MDM checkpoint and adjacent args.json are required')
        return MDMModel(repository, checkpoint.resolve(), python_path or sys.executable)


@param('seed', Random(), default=42)
@param('seconds', Slider(1, 9, 0.5), default=2.0)
def MDMTextToMotion(config: SSUIConfig, model: MDMModel, prompt: Prompt) -> Motion:
    if config.is_prepare():
        return Motion(np.empty((0, 22, 3)), 20.0, Path(), '')
    root = Path(os.environ.get('SSUI_MODEL_OUTPUT_DIR', 'output/motion')).resolve()
    root.mkdir(parents=True, exist_ok=True)
    output = Path(tempfile.mkdtemp(prefix='mdm-', dir=root))
    runner = Path(__file__).with_name('mdm_runner.py')
    subprocess.run([
        model.python, str(runner), '--repo', str(model.repository),
        '--model_path', str(model.checkpoint), '--text_prompt', prompt.text,
        '--num_samples', '1', '--num_repetitions', '1',
        '--motion_length', str(config['seconds']), '--seed', str(config['seed']),
        '--output_dir', str(output),
    ], check=True, timeout=1200, env={**os.environ, 'MPLBACKEND': 'Agg'})
    # Read only the trusted local output generated by this subprocess.
    data = np.load(output / 'results.npy', allow_pickle=True).item()
    length = int(data['lengths'][0])
    joints = np.asarray(data['motion'][0, :, :, :length]).transpose(2, 0, 1)
    if joints.shape != (length, 22, 3) or length < 2 or not np.isfinite(joints).all():
        raise RuntimeError('MDM produced an invalid HumanML joint trajectory')
    motion = Motion(joints, 20.0, output, prompt.text)
    motion.export(str(output / 'motion.npz'))
    return motion
